export type ArtifactFamily = keyof typeof REQUIRED_SURFACES_BY_FAMILY;
export type EvalSurface = {
  [Family in ArtifactFamily]: (typeof REQUIRED_SURFACES_BY_FAMILY)[Family][number];
}[ArtifactFamily];

export type EditRisk = 'read-only' | 'guarded-edit' | 'destructive-edit';
export type PreviewPolicy = 'required' | 'not-needed' | 'not-supported';
export type ToolProfile = 'facade-first' | 'authoring' | 'advanced-full' | 'filesystem-plugin';
export type WorkflowExecution = 'replayable' | 'static' | 'app-only';
export type CanonicalReplayScenarioId =
  | 'active-external-reference-routing'
  | 'batch-vs-single-edit'
  | 'stale-guard-refresh-retry'
  | 'dry-run-first-destructive-edit'
  | 'no-file-open-workflow'
  | 'charx-facade-indexed-mutations'
  | 'charx-manage-items-families'
  | 'risup-facade-indexed-mutations'
  | 'risup-manage-items-workflows'
  | 'risup-formatting-order-authoring'
  | 'risup-project-file-roundtrip'
  | 'risum-facade-surface-roundtrip';

export interface WorkflowRoute {
  profile: ToolProfile;
  discover: readonly string[];
  readOrSearch: readonly string[];
  preview: readonly string[];
  apply: readonly string[];
  validate: readonly string[];
  granularFallbackReason?: string;
}

export interface WorkflowSafety {
  boundedOrItemizedRead: boolean;
  batchWhenSiblingItems: boolean;
  staleGuards: readonly string[];
  previewPolicy: PreviewPolicy;
  wrongTargetAvoidance: readonly string[];
  postEditValidation: readonly string[];
}

export interface WorkflowEvalTask {
  id: string;
  prompt: string;
  family: ArtifactFamily;
  corpusRoots: readonly string[];
  sourceOfTruth: readonly string[];
  surfaces: readonly EvalSurface[];
  editRisk: EditRisk;
  execution: WorkflowExecution;
  replayScenarioIds?: readonly CanonicalReplayScenarioId[];
  route: WorkflowRoute;
  safety: WorkflowSafety;
}

