export function getAvatarDialogueLines(themeId: ThemeId, darkMode: boolean, active: boolean): readonly string[] {
  const fallbackTheme: BuiltInThemeId = darkMode ? 'aris' : 'toki';
  const dialogue = themeId === 'custom' ? CHARACTER_DIALOGUE[fallbackTheme] : CHARACTER_DIALOGUE[themeId];
  return active ? dialogue.working : dialogue.idle;
}

export function getAvatarDialogueLine(themeId: ThemeId, darkMode: boolean, active: boolean): string {
  const lines = getAvatarDialogueLines(themeId, darkMode, active);
  return lines[Math.floor(Math.random() * lines.length)];
}
